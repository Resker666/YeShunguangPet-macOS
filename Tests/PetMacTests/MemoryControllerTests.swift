import Foundation
import XCTest
import PetCore

@MainActor final class MemoryControllerTests: XCTestCase {
    private func fixture(canDispatch: @escaping () -> Bool = { true }) async throws -> (ChatControllerFixture, ChatMemory) {
        let f = try ChatControllerFixture(canDispatch: canDispatch)
        addTeardownBlock { await f.close() }
        let first = try ChatMemory(text: "旧称呼")
        let state = try ChatConversation(characterID: "robin", profile: .init(background: "原背景"), memories: [first, ChatMemory(text: "喜欢茶")], memoryRevision: 2).appending(user: "旧问", assistant: "旧答")
        try ChatStore(directory: f.root.appendingPathComponent("AI/characters")).save(state)
        try await f.open()
        return (f, first)
    }
    func testMemoryMutationsCommitBeforeBecomingEffective() async throws {
        let (f, first) = try await fixture()
        let context = try XCTUnwrap(f.controller.character)
        await f.persistence.holdNextWrite()
        f.controller.saveMemory(id: first.id, text: " 新称呼 ", for: context, expectedRevision: 2)
        await f.persistence.waitForOperations(1)
        XCTAssertEqual(f.controller.conversation?.memories.first?.text, "旧称呼")
        XCTAssertFalse(f.controller.canEditMemories)
        await f.persistence.releaseWrite(); await f.controller.waitForPendingWrites()
        XCTAssertEqual(f.controller.conversation?.memories.first?.text, "新称呼")
        XCTAssertEqual(f.controller.conversation?.memoryRevision, 3)
        f.controller.deleteMemory(id: first.id, for: context, expectedRevision: 3)
        await f.controller.waitForPendingWrites()
        XCTAssertEqual(f.controller.conversation?.memories.map(\.text), ["喜欢茶"])
        f.controller.clearMemories(for: context, expectedRevision: 4)
        await f.controller.waitForPendingWrites()
        XCTAssertEqual(f.controller.conversation?.memories.count, 0)
        XCTAssertEqual(f.controller.conversation?.memoryRevision, 5)
        XCTAssertEqual(f.controller.conversation?.profile.background, "原背景")
        XCTAssertEqual(f.controller.conversation?.messages.map(\.content), ["旧问", "旧答"])
    }
    func testFailedConfirmedChangeSurvivesWindowCloseSkinChangeAndTermination() async throws {
        let (f, first) = try await fixture()
        let context = try XCTUnwrap(f.controller.character)
        await f.persistence.failNext("memories:robin")
        f.controller.saveMemory(id: first.id, text: "待存称呼", for: context, expectedRevision: 2)
        await f.controller.waitForPendingWrites()
        XCTAssertEqual(f.controller.pendingMemoryCharacterIDs, ["robin"])
        XCTAssertEqual(f.controller.state, .unsavedMemory)
        f.controller.setDraft("不能发"); XCTAssertFalse(f.controller.canSend)
        f.controller.windowClosed()
        try await f.open("hutao")
        f.controller.setDraft("另一角色可用"); XCTAssertTrue(f.controller.canSend)
        try await f.open("robin", revision: 1)
        XCTAssertEqual(f.controller.conversation?.memories.first?.text, "旧称呼")
        XCTAssertTrue(f.controller.canRetryMemorySave)
        f.controller.beginTermination()
        XCTAssertNotNil(f.controller.terminationSaveError)
        let saved = await f.controller.retryAllPendingSaves()
        XCTAssertTrue(saved)
        XCTAssertTrue(f.controller.pendingMemoryCharacterIDs.isEmpty)
        XCTAssertEqual(f.controller.conversation?.memories.first?.text, "待存称呼")
        XCTAssertEqual(f.controller.conversation?.memoryRevision, 3)
        XCTAssertEqual(f.client.count, 0)
        let reads = await f.credentials.reads; XCTAssertEqual(reads, 0)
    }
    func testAcceptedMemoryWriteFinishesAfterClosing() async throws {
        let (f, first) = try await fixture()
        let context = try XCTUnwrap(f.controller.character)
        await f.persistence.holdNextWrite()
        f.controller.saveMemory(id: first.id, text: "旧角色确认", for: context, expectedRevision: 2)
        await f.persistence.waitForOperations(1)
        f.controller.windowClosed(); try await f.open("hutao")
        await f.persistence.releaseWrite(); await f.controller.waitForPendingWrites()
        XCTAssertEqual(f.controller.character?.id, "hutao")
        XCTAssertTrue(f.controller.conversation?.memories.isEmpty == true)
        try await f.open("robin")
        XCTAssertEqual(f.controller.conversation?.memories.first?.text, "旧角色确认")
        XCTAssertTrue(f.feedback.lines.isEmpty)
    }
    func testMemoryGatesAndDiscardPreserveOldEffectiveState() async throws {
        let modal = ChatTestFlag()
        let (f, first) = try await fixture(canDispatch: { !modal.value })
        let context = try XCTUnwrap(f.controller.character)
        let stale = ChatCharacter(id: context.id, name: context.name, description: context.description, skinRevision: 99)
        f.controller.saveMemory(id: first.id, text: "stale", for: stale, expectedRevision: 2)
        f.controller.saveMemory(id: first.id, text: "stale", for: context, expectedRevision: 1)
        modal.value = true
        f.controller.saveMemory(id: first.id, text: "modal", for: context, expectedRevision: 2)
        modal.value = false; f.controller.setSleeping(true)
        f.controller.saveMemory(id: first.id, text: "sleep", for: context, expectedRevision: 2)
        f.controller.setSleeping(false)
        let operations = await f.persistence.operations; XCTAssertTrue(operations.isEmpty)
        f.controller.saveConnection(.init(enabled: false)); await f.controller.waitForPendingWrites()
        XCTAssertTrue(f.controller.canEditMemories)
        await f.persistence.failNext("memories:robin")
        f.controller.deleteMemory(id: first.id, for: context, expectedRevision: 2)
        await f.controller.waitForPendingWrites()
        f.controller.clearHistory()
        XCTAssertEqual(f.controller.conversation?.messages.count, 2)
        f.controller.discardPendingMemorySave()
        XCTAssertTrue(f.controller.canEditMemories)
        XCTAssertEqual(f.controller.conversation?.memories.first?.text, "旧称呼")
        XCTAssertNil(f.controller.terminationSaveError)
    }
}
